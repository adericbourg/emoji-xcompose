#!/bin/sh
# Install emoji Compose sequences for the current user. Safe to re-run.
# Checks everything first; changes nothing unless all required checks pass.
set -eu

cd "$(dirname "$0")"
conf="$HOME/.XCompose"
out="$HOME/.XCompose.emoji"
marker='# Generated by emoji-xcompose'
failed=0

ok()   { printf '  [ok]   %s\n' "$1"; }
warn() { printf '  [warn] %s\n' "$1"; }
fail() { printf '  [FAIL] %s\n' "$1"; failed=1; }

echo "Required:"
if ! command -v python3 >/dev/null 2>&1; then
    fail "python3 not found. Install it with your package manager (e.g. apt/dnf/pacman install python3)."
elif ! python3 -c 'import sys; sys.exit(sys.version_info < (3, 6))' 2>/dev/null; then
    fail "python3 3.6 or newer needed, found $(python3 --version 2>&1)."
else
    ok "python3 $(python3 -c 'import platform; print(platform.python_version())')"
fi
for tool in grep cp date head; do
    if command -v "$tool" >/dev/null 2>&1; then ok "$tool"; else fail "$tool not found."; fi
done
if [ -w "$HOME" ]; then ok "home directory is writable ($HOME)"; else fail "$HOME is not writable."; fi
if [ -e "$conf" ] && [ ! -w "$conf" ]; then fail "$conf exists but is not writable."; fi
if [ -e "$out" ] && ! grep -qF "$marker" "$out"; then
    fail "$out exists and was not created by emoji-xcompose. Move it away and run again."
fi
echo "  [info] network access to raw.githubusercontent.com is checked during the download."

echo
echo "Your setup (informational, never blocks the install):"
compose=$( { printf '%s\n' "${XKB_DEFAULT_OPTIONS:-}"
             cat "$HOME/.config/kxkbrc" 2>/dev/null
             gsettings get org.gnome.desktop.input-sources xkb-options 2>/dev/null
             setxkbmap -query 2>/dev/null; } | grep -o 'compose:[a-z0-9_]*' | head -n 1 ) || true
if [ -n "$compose" ]; then
    ok "Compose key configured ($compose)"
else
    warn "no Compose key found in KDE, GNOME, XKB_DEFAULT_OPTIONS or setxkbmap. Set one in your keyboard settings (e.g. Right Alt), unless it is configured elsewhere (sway, Hyprland, ...)."
fi
if [ -n "${XCOMPOSEFILE:-}" ]; then
    warn "XCOMPOSEFILE=$XCOMPOSEFILE is set: applications read that file instead of $conf. Add the line 'include \"%H/.XCompose.emoji\"' to it, or unset XCOMPOSEFILE."
else
    ok "XCOMPOSEFILE not set, so $conf is used"
fi
charmap=$(locale charmap 2>/dev/null) || charmap="${LC_ALL:-${LC_CTYPE:-${LANG:-}}}"
case "$charmap" in
    *UTF-8*|*utf8*) ok "UTF-8 locale" ;;
    *) warn "locale is not UTF-8 (${charmap:-unset}): emoji may not be typed correctly." ;;
esac
im="${GTK_IM_MODULE:-${QT_IM_MODULE:-}}"
if [ -n "$im" ]; then
    ok "input method $im: it handles Compose itself and also reads $conf"
else
    ok "no input method set: Compose is handled by the toolkit (libxkbcommon, GTK)"
fi
ok "session: ${XDG_SESSION_TYPE:-unknown}, desktop: ${XDG_CURRENT_DESKTOP:-unknown}"

echo
if [ "$failed" -ne 0 ]; then
    echo "Nothing was changed. Fix the [FAIL] items above and run again."
    exit 1
fi

echo "Downloading the emoji lists and generating $out..."
python3 gen_emoji_xcompose.py "$out" || { echo "Nothing was changed."; exit 1; }

inc='include "%H/.XCompose.emoji"'
if [ ! -e "$conf" ]; then
    # %L keeps the system Compose sequences of the current locale.
    printf 'include "%%L"\n%s\n' "$inc" > "$conf"
    echo "Created $conf"
elif ! grep -qF "$inc" "$conf"; then
    bak="$conf.bak.$(date +%Y%m%d-%H%M%S)"
    cp -p "$conf" "$bak"
    printf '%s\n' "$inc" >> "$conf"
    echo "Added the emoji include to $conf (backup: $bak)"
else
    echo "$conf already includes the emoji file"
fi

echo "Done. Log out and back in for running applications to pick it up."
